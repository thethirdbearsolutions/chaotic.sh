"""One membership per user per team (CHT-1791): UNIQUE(team_id, user_id)
on team_members.

The create_index below was generated by `oxyde makemigrations --name
team_members_unique` (one create_index, which it can do on SQLite) and
is declared in `OxydeTeamMember.Meta.indexes` under the same name
(CHT-1410). Until now a second membership row was kept out only by
application checks (TeamService.accept_invitation's get_member before
its insert), which hold only because SQLite serialises writers.

Existing duplicates are removed first, through ctx.execute (data, not
schema, so the replay ignores it). For each (team_id, user_id) with
more than one row, exactly one row is kept:

  1. the most privileged role: OWNER, then ADMIN, then MEMBER (the order
     of TeamRole). The role column stores the enum name (0007); the
     value and the `TeamRole.X` spelling written before CHT-998 rank the
     same, and anything else ranks below MEMBER;
  2. then the earliest joined_at;
  3. then the lowest id.

The others are deleted. A row is all a membership is: no table has a
foreign key to team_members.id, and nothing stores a membership's id
(everything that refers to a membership does so by team_id and
user_id), so there is nothing to repoint. Rows with a NULL user_id are
left alone: SQLite's unique index treats NULLs as distinct, so they do
not conflict, and they are not memberships of any one user.

The removal is reported, not silent: before anything is written the
migration reads the rows it will delete through its own Oxyde
connection (never Python's sqlite3, CHT-1491) and prints one line per
row (id, team, user, role, joined_at) and a total, visible in
`oxyde migrate` / `chaotic system upgrade` output. Migration execution
is transactional, so if it fails after printing nothing was deleted.
On a context with no connection to read through, it prints a one-line
notice instead; the dedupe happens either way. To check before
upgrading (read-only):

    SELECT team_id, user_id, count(*) FROM team_members
    WHERE user_id IS NOT NULL GROUP BY team_id, user_id HAVING count(*) > 1;

The downgrade drops the index. Deleted duplicates are not restored.

Created: 2026-10-15 10:45:43
"""

depends_on = "0032_email_verification"

# Lower is more privileged. Every spelling of a role ever stored.
_ROLE_RANK = (
    "CASE "
    "WHEN role IN ('OWNER', 'owner', 'TeamRole.OWNER') THEN 0 "
    "WHEN role IN ('ADMIN', 'admin', 'TeamRole.ADMIN') THEN 1 "
    "WHEN role IN ('MEMBER', 'member', 'TeamRole.MEMBER') THEN 2 "
    "ELSE 3 END"
)

# The rows the dedupe deletes: every row of a (team_id, user_id) group
# but the one that sorts first. The report and the DELETE share it, so
# what is printed is what is removed.
LOSERS_SQL = (
    "SELECT id, team_id, user_id, role, joined_at FROM ("
    "SELECT id, team_id, user_id, role, joined_at, ROW_NUMBER() OVER ("
    "PARTITION BY team_id, user_id "
    f"ORDER BY {_ROLE_RANK}, joined_at IS NULL, joined_at, id"
    ") AS keep_rank FROM team_members WHERE user_id IS NOT NULL"
    ") WHERE keep_rank > 1"
)

DEDUPE_SQL = f"DELETE FROM team_members WHERE id IN (SELECT id FROM ({LOSERS_SQL}))"


def _read_through_oxyde(database, sql: str, params: list) -> list[dict]:
    """Rows of `sql` (as dicts keyed by column name), read through Oxyde's
    own connection to the migration target. (0022's, copied so a later
    edit there cannot change this migration.)

    Never sqlite3.connect() the target here: Oxyde links its own copy of
    SQLite, POSIX locks are per process, and a second copy opening the
    same WAL database truncates the -shm Oxyde has mapped and drops its
    locks on close (CHT-1491). upgrade() is synchronous and runs inside
    the executor's event loop, so the query runs on a short-lived thread
    with an event loop of its own.
    """
    import asyncio
    import threading

    from oxyde import execute_raw

    outcome = {}

    def run():
        try:
            outcome["rows"] = asyncio.run(execute_raw(sql, params, client=database))
        except BaseException as error:  # re-raised on the migration's thread
            outcome["error"] = error

    reader = threading.Thread(target=run, name="migration-0033-read")
    reader.start()
    reader.join()
    if "error" in outcome:
        raise outcome["error"]
    return outcome["rows"]


def _recording(ctx) -> bool:
    """True in the replay (collect mode); see 0017."""
    return getattr(ctx, "_mode", "execute") == "collect"


def report_duplicates(ctx, echo=print) -> int | None:
    """Print one line per membership row the dedupe will delete, and a
    total. Returns how many, or None when there was no connection to read
    through. Silent in the replay, which has nothing to scan (CHT-1402).
    """
    if _recording(ctx):
        return None
    database = getattr(ctx, "_db_conn", None)
    if (
        getattr(ctx, "dialect", "sqlite") != "sqlite"
        or database is None
        or not callable(getattr(database, "execute", None))
    ):
        echo(
            "[0033] cannot pre-scan team_members for duplicate memberships (no SQLite "
            "connection to read through); any duplicates will still be removed, keeping "
            "the most privileged, earliest-joined row of each (team_id, user_id)."
        )
        return None
    losers = _read_through_oxyde(database, LOSERS_SQL, [])
    for row in losers:
        echo(
            f"[0033] duplicate team membership -- deleting row {row['id']} "
            f"(team {row['team_id']}, user {row['user_id']}, role {row['role']}, "
            f"joined {row['joined_at']})"
        )
    if losers:
        echo(f"[0033] removing {len(losers)} duplicate team_members row(s)")
    return len(losers)


def upgrade(ctx):
    """Apply migration."""
    report_duplicates(ctx)
    ctx.execute(DEDUPE_SQL)
    ctx.create_index("team_members", {
    'name': 'ux_team_members_team_user',
    'fields': [
        'team_id',
        'user_id'
    ],
    'unique': True,
    'method': None
})


def downgrade(ctx):
    """Revert migration."""
    ctx.drop_index("team_members", "ux_team_members_team_user")
