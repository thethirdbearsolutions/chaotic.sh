"""One account per address, ignoring case, in the database (CHT-1804):
users.email_folded, and a UNIQUE index on it.

Until now signup refused an address that differs from an existing one
only in case (CHT-1790) in the application alone, so two signups racing
each other could both pass, and older databases may already hold such
pairs. Two accounts at one address (ignoring case) share one
email-verification rate-limit bucket, so either can lock the other out.

The add_column and create_index below were generated by `oxyde
makemigrations --name users_email_folded` (both are operations it can
do on SQLite), and the index is declared in `OxydeUser.Meta.indexes`
under the same name (CHT-1410). The backfill between them is data, not
schema, so it goes through ctx.execute and the replay ignores it.

The backfill never changes or deletes an account, and never touches
`email`: it only fills the new column. Each account's folded address is
computed in Python by `fold_email` below, a copy of
`app.utils.email_address.fold_email` (copied so a later edit there
cannot change this migration; a test pins the two together): whitespace
of every kind stripped from both ends, ASCII letters lowercased. SQL's
trim() strips spaces only, so it is not used (review of PR #437). The
accounts are read through the migration's own Oxyde connection (never
Python's sqlite3, CHT-1491) before anything is written, and one UPDATE
per account is queued, the value as a quoted literal (ctx.execute
takes no parameters).

Where several accounts fold to the same address, only the oldest
(lowest created_at, then id) gets it; the others keep NULL, which the
unique index allows (NULLs are distinct). Those accounts keep working:
they log in by their exact address as before. They are reported, not
silent: one line per account, by id only (no address), and a total,
visible in `oxyde migrate` / `chaotic system upgrade` output. The
server also logs a warning at every startup while any account has a
NULL email_folded. Migration execution is transactional, so if it fails
after printing nothing was written. Stop the server before migrating
(as `chaotic system upgrade` does): an account created between the read
and the write would be left NULL, and the startup warning would count
it. To check for case variants before upgrading (read-only; this query
trims spaces only):

    SELECT lower(trim(email)), count(*) FROM users
    GROUP BY lower(trim(email)) HAVING count(*) > 1;

On a context with no SQLite connection to read through, the backfill
falls back to lower(trim(email)) in SQL, and says so.

The downgrade drops the index and the column. No address is lost
either way.

Created: 2026-10-15 12:55:15
"""

depends_on = "0033_team_members_unique"

_ASCII_FOLD = str.maketrans("ABCDEFGHIJKLMNOPQRSTUVWXYZ", "abcdefghijklmnopqrstuvwxyz")


def fold_email(email: str) -> str:
    """app.utils.email_address.fold_email as of this migration."""
    return (email or "").strip().translate(_ASCII_FOLD)


# Every account, oldest first.
ACCOUNTS_SQL = "SELECT id, email FROM users ORDER BY created_at, id"

# The fallback with no connection to read through: SQL's fold, which
# strips spaces only. Only the oldest account per address gets it.
FALLBACK_FOLD_SQL = "lower(trim(email))"
FALLBACK_BACKFILL_SQL = (
    f"UPDATE users SET email_folded = {FALLBACK_FOLD_SQL} WHERE id IN ("
    f"SELECT id FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY {FALLBACK_FOLD_SQL} "
    "ORDER BY created_at, id) AS fold_rank FROM users) WHERE fold_rank = 1)"
)


def sql_literal(value: str) -> str:
    """``value`` as an SQLite string literal. A NUL cannot be written as
    one; plan_backfill never hands this an address that has one, so only
    an id can, and that stops the migration, saying which id."""
    if "\x00" in value:
        raise ValueError(
            f"[0034] users.id {value!r} contains a NUL character, which cannot be written "
            "in the backfill's SQL; fix that row's id, then migrate again"
        )
    return "'" + value.replace("'", "''") + "'"


def plan_backfill(
    accounts: list[dict],
) -> tuple[dict[str, str], dict[str, str], dict[str, str]]:
    """From ``accounts`` (dicts with id and email, oldest first):

    - the folded address each holder gets ({id: folded});
    - the accounts left NULL because an older account holds their
      address ({id: holder id});
    - the accounts left NULL because their address cannot be folded
      ({id: why}): not text (a BLOB the driver hands back as bytes, or
      anything else), or text with a NUL character. They take no part
      in the grouping, so they are never reported as duplicates and
      never hold an address.
    """
    holders: dict[str, str] = {}
    folded_by_id: dict[str, str] = {}
    excluded: dict[str, str] = {}
    unreadable: dict[str, str] = {}
    for row in accounts:
        email = row["email"]
        if not isinstance(email, str):
            unreadable[row["id"]] = "email unreadable"
            continue
        if "\x00" in email:
            unreadable[row["id"]] = "email contains a NUL character"
            continue
        folded = fold_email(email)
        if folded in holders:
            excluded[row["id"]] = holders[folded]
        else:
            holders[folded] = row["id"]
            folded_by_id[row["id"]] = folded
    return folded_by_id, excluded, unreadable


def _read_through_oxyde(database, sql: str, params: list) -> list[dict]:
    """Rows of `sql` (as dicts keyed by column name), read through Oxyde's
    own connection to the migration target. (0033's, copied so a later
    edit there cannot change this migration.)

    Never sqlite3.connect() the target here: Oxyde links its own copy of
    SQLite, POSIX locks are per process, and a second copy opening the
    same WAL database truncates the -shm Oxyde has mapped and drops its
    locks on close (CHT-1491). upgrade() is synchronous and runs inside
    the executor's event loop, so the query runs on a short-lived thread
    with an event loop of its own.
    """
    import asyncio
    import threading

    from oxyde import execute_raw

    outcome = {}

    def run():
        try:
            outcome["rows"] = asyncio.run(execute_raw(sql, params, client=database))
        except BaseException as error:  # re-raised on the migration's thread
            outcome["error"] = error

    reader = threading.Thread(target=run, name="migration-0034-read")
    reader.start()
    reader.join()
    if "error" in outcome:
        raise outcome["error"]
    return outcome["rows"]


def _recording(ctx) -> bool:
    """True in the replay (collect mode); see 0017."""
    return getattr(ctx, "_mode", "execute") == "collect"


def backfill(ctx, echo=print) -> int | None:
    """Queue the UPDATEs that fill email_folded, and print one line per
    account left NULL (ids only) and a total of the duplicates. Returns
    how many were left NULL (duplicates and unreadable addresses), or None when there was no connection to read through (the SQL
    fallback is queued instead). Nothing in the replay, which has no
    rows (CHT-1402).
    """
    if _recording(ctx):
        return None
    database = getattr(ctx, "_db_conn", None)
    if (
        getattr(ctx, "dialect", "sqlite") != "sqlite"
        or database is None
        or not callable(getattr(database, "execute", None))
    ):
        echo(
            "[0034] cannot read users to fold their addresses (no SQLite connection to read "
            "through); folding in SQL with lower(trim(email)) instead, which trims spaces only. "
            "Accounts sharing an address are kept, with only the oldest of each holding it; "
            "the server warns at startup if any are left without one."
        )
        ctx.execute(FALLBACK_BACKFILL_SQL)
        return None
    accounts = _read_through_oxyde(database, ACCOUNTS_SQL, [])
    folded_by_id, excluded, unreadable = plan_backfill(accounts)
    for user_id, folded in folded_by_id.items():
        ctx.execute(
            f"UPDATE users SET email_folded = {sql_literal(folded)} WHERE id = {sql_literal(user_id)}"
        )
    for user_id, why in unreadable.items():
        echo(f"[0034] account {user_id!s} {why}; email_folded left NULL")
    for user_id, holder_id in excluded.items():
        echo(
            f"[0034] account {user_id} shares its address (ignoring case) with older account "
            f"{holder_id}; email_folded left NULL, account unchanged"
        )
    if excluded:
        echo(
            f"[0034] {len(excluded)} account(s) left without email_folded; they keep their "
            "address and can still log in with it exactly"
        )
    return len(excluded) + len(unreadable)


def upgrade(ctx):
    """Apply migration."""
    ctx.add_column("users", {
    'name': 'email_folded',
    'python_type': 'str',
    'db_type': None,
    'nullable': True,
    'primary_key': False,
    'unique': False,
    'default': None,
    'auto_increment': False,
    'max_length': None,
    'max_digits': None,
    'decimal_places': None
})
    backfill(ctx)
    ctx.create_index("users", {
    'name': 'ux_users_email_folded',
    'fields': [
        'email_folded'
    ],
    'unique': True,
    'method': None
})


def downgrade(ctx):
    """Revert migration."""
    ctx.drop_index("users", "ux_users_email_folded")
    ctx.drop_column("users", "email_folded")
