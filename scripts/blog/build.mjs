#!/usr/bin/env node
// Builds the blog: the index, one page per post, and the RSS feed.
//
//   node scripts/blog/build.mjs           write the output
//   node scripts/blog/build.mjs --check   exit 1 if the committed output is stale
//
// Inputs, all in this folder (none of it is served):
//   site.json    the blog's title, description, URL and output folder
//   posts.json   the published posts, newest first or in any order:
//                [{ "slug", "title", "date": "YYYY-MM-DD", "description" }]
//   posts/<slug>.html   each post's body, plain HTML; its <h2>s make the
//                       table of contents
//   layout.html  the page around everything, with {{placeholders}}
//
// No dependencies; Node 18 or newer.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const MARK = "<!-- generated by scripts/blog/build.mjs; edit scripts/blog/, not this file -->";

const site = JSON.parse(readFileSync(join(HERE, "site.json"), "utf8"));
const posts = JSON.parse(readFileSync(join(HERE, "posts.json"), "utf8"));
const layout = readFileSync(join(HERE, "layout.html"), "utf8");
const outDir = resolve(HERE, site.outDir);
const blogUrl = site.siteUrl.replace(/\/$/, "") + site.blogPath;

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function fail(msg) {
  console.error(`blog: ${msg}`);
  process.exit(2);
}

// --- validate ---------------------------------------------------------------
if (!Array.isArray(posts)) fail("posts.json must be an array");
const seen = new Set();
for (const p of posts) {
  for (const k of ["slug", "title", "date", "description"]) {
    if (typeof p[k] !== "string" || !p[k].trim()) fail(`post ${JSON.stringify(p.slug)} is missing "${k}"`);
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(p.slug)) fail(`slug "${p.slug}" must be lowercase words joined by hyphens`);
  if (["rss.xml", "blog.css"].includes(p.slug)) fail(`slug "${p.slug}" is reserved`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(p.date) || isNaN(Date.parse(p.date))) fail(`post "${p.slug}" date must be YYYY-MM-DD`);
  if (seen.has(p.slug)) fail(`slug "${p.slug}" appears twice`);
  seen.add(p.slug);
  if (!existsSync(join(HERE, "posts", `${p.slug}.html`))) fail(`posts/${p.slug}.html is missing`);
}
const sorted = [...posts].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));

// --- render -----------------------------------------------------------------
function page({ title, description, canonical, body }) {
  const vars = {
    title: esc(title),
    description: esc(description),
    canonical: esc(canonical),
    feed_url: esc(site.blogPath + "rss.xml"),
    feed_title: esc(site.title),
    blog_path: esc(site.blogPath),
    body,
  };
  const html = layout.replace(/\{\{(\w+)\}\}/g, (m, k) => {
    if (!(k in vars)) fail(`layout.html uses unknown placeholder {{${k}}}`);
    return vars[k];
  });
  // The marker goes after the doctype, so it can't put a browser in quirks mode.
  return /^<!doctype html>/i.test(html) ? html.replace(/^(<!doctype html>)\n?/i, `$1\n${MARK}\n`) : `${MARK}\n${html}`;
}

const prettyDate = (d) =>
  new Date(d + "T12:00:00Z").toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });

function indexBody() {
  const head = `<header class="blog-head">
  <h1>${esc(site.heading || site.title)}</h1>
  <p class="blog-lead">${esc(site.description)} <a href="${esc(site.blogPath)}rss.xml">RSS</a></p>
</header>`;
  if (!sorted.length) {
    return `${head}
<p class="blog-empty">No posts yet. The <a href="${esc(site.blogPath)}rss.xml">RSS feed</a> is live, so a reader that subscribes now gets the first one.</p>`;
  }
  const items = sorted
    .map(
      (p) => `  <li><a class="post-card" href="${esc(site.blogPath + p.slug)}/">
    <time datetime="${p.date}">${prettyDate(p.date)}</time>
    <strong>${esc(p.title)}</strong>
    <span>${esc(p.description)}</span>
  </a></li>`
    )
    .join("\n");
  return `${head}
<ol class="post-list">
${items}
</ol>`;
}

const slugify = (s) =>
  s.toLowerCase().replace(/<[^>]+>/g, "").replace(/&[a-z#0-9]+;/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "section";

function postBody(p) {
  let html = readFileSync(join(HERE, "posts", `${p.slug}.html`), "utf8");
  const toc = [];
  const used = new Set();
  html = html.replace(/<h2(\s[^>]*)?>([\s\S]*?)<\/h2>/g, (m, attrs = "", inner) => {
    let id = (attrs.match(/\sid="([^"]+)"/) || [])[1];
    if (!id) {
      id = slugify(inner);
      while (used.has(id)) id += "-2";
      attrs += ` id="${id}"`;
    }
    used.add(id);
    toc.push({ id, text: inner.replace(/<[^>]+>/g, "").trim() });
    return `<h2${attrs}>${inner}</h2>`;
  });
  const tocHtml = toc.length
    ? `<nav class="toc" aria-label="On this page"><details open><summary>On this page</summary><ol>
${toc.map((t) => `  <li><a href="#${esc(t.id)}">${esc(t.text)}</a></li>`).join("\n")}
</ol></details></nav>`
    : "";
  return `<div class="post-layout${toc.length ? " has-toc" : ""}">
${tocHtml}
<article class="post">
<header class="post-head">
  <p class="post-meta"><a href="${esc(site.blogPath)}">Blog</a> · <time datetime="${p.date}">${prettyDate(p.date)}</time></p>
  <h1>${esc(p.title)}</h1>
  <p class="post-desc">${esc(p.description)}</p>
</header>
${html.trim()}
</article>
</div>
<script src="${esc(site.blogPath)}toc.js" defer></script>`;
}

const rfc822 = (d) => new Date(d + "T12:00:00Z").toUTCString();

function rss() {
  const items = sorted
    .map((p) => {
      const link = blogUrl + p.slug + "/";
      return `    <item>
      <title>${esc(p.title)}</title>
      <link>${esc(link)}</link>
      <guid isPermaLink="true">${esc(link)}</guid>
      <pubDate>${rfc822(p.date)}</pubDate>
      <description>${esc(p.description)}</description>
    </item>`;
    })
    .join("\n");
  const built = sorted.length ? `\n    <lastBuildDate>${rfc822(sorted[0].date)}</lastBuildDate>` : "";
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>${esc(site.title)}</title>
    <link>${esc(blogUrl)}</link>
    <description>${esc(site.description)}</description>
    <language>${esc(site.language || "en")}</language>
    <atom:link href="${esc(blogUrl)}rss.xml" rel="self" type="application/rss+xml"/>${built}
${items ? items + "\n" : ""}  </channel>
</rss>
`;
}

const files = new Map();
files.set("index.html", page({ title: site.title, description: site.description, canonical: blogUrl, body: indexBody() }));
files.set("rss.xml", rss());
for (const p of sorted) {
  files.set(
    `${p.slug}/index.html`,
    page({ title: `${p.title} · ${site.title}`, description: p.description, canonical: `${blogUrl}${p.slug}/`, body: postBody(p) })
  );
}

// Post folders this script made earlier for posts that are gone.
const stale = existsSync(outDir)
  ? readdirSync(outDir, { withFileTypes: true })
      .filter((d) => d.isDirectory() && !seen.has(d.name))
      .map((d) => join(d.name, "index.html"))
      .filter((f) => existsSync(join(outDir, f)) && readFileSync(join(outDir, f), "utf8").slice(0, 300).includes(MARK))
  : [];

// --- write or check ---------------------------------------------------------
if (process.argv.includes("--check")) {
  const wrong = [...files].filter(([f, body]) => !existsSync(join(outDir, f)) || readFileSync(join(outDir, f), "utf8") !== body);
  const problems = [...wrong.map(([f]) => `stale: ${f}`), ...stale.map((f) => `left over: ${f}`)];
  if (problems.length) {
    console.error(problems.join("\n") + "\nblog: run `node scripts/blog/build.mjs` and commit the result");
    process.exit(1);
  }
  console.log(`blog: up to date (${sorted.length} post${sorted.length === 1 ? "" : "s"})`);
} else {
  for (const [f, body] of files) {
    mkdirSync(dirname(join(outDir, f)), { recursive: true });
    writeFileSync(join(outDir, f), body);
  }
  for (const f of stale) rmSync(dirname(join(outDir, f)), { recursive: true });
  console.log(`blog: wrote ${files.size} file${files.size === 1 ? "" : "s"} to ${site.outDir} (${sorted.length} post${sorted.length === 1 ? "" : "s"})`);
}
